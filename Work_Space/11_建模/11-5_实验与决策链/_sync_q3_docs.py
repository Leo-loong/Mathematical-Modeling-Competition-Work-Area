# 待裁定横幅（整块）→ 移除
BANNER_Q3 = re.compile(r">\s*##\s*⚠⚠?\s*待裁定.*?(?=\n[^>]|\Z)", re.S)


def process(path):
    if not os.path.isfile(path):
        return None
    txt = io.open(path, encoding='utf-8').read()
    orig = txt
    n_tab = 0
    # 1) 表 5 整块重写
    lines = txt.split('\n')
    out = []
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.strip().startswith('| 时间/h') and '0.5 cm' in ln:
            j = i
            while j < len(lines) and lines[j].strip().startswith('|'):
                j += 1
            out.extend(NEW_TABLE.split('\n'))
            n_tab += 1
            i = j
            continue
        out.append(ln)
        i += 1
    txt = '\n'.join(out)
    # 2) 标量替换
    n_rep = 0
    for a, b in REP:
        c = txt.count(a)
        if c:
            txt = txt.replace(a, b)
            n_rep += c
    # 3) 移除"待裁定"横幅（已裁定/已修复）
    txt2 = BANNER_Q3.sub('', txt)
    flag_ban = '有' if txt2 != txt else '无'
    txt = txt2
    if txt != orig:
        io.open(path, 'w', encoding='utf-8').write(txt)
        return (n_tab, n_rep, flag_ban)
    return (0, 0, '无')


