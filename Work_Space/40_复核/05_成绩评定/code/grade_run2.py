# ============================================================ 五、计算与输出
def r1(x):
    return math.floor(x * 10.0 + 0.5 + 1e-9) / 10.0


def r2(x):
    return math.floor(x * 100.0 + 0.5 + 1e-9) / 100.0


def fold(m, judges):
    lo_cut = hi_cut = 0.0
    for j in judges:
        a, b = RATIO.get(j, (0.0, 0.0))
        lo_cut += a
        hi_cut += b
    hi = max(0.0, m - lo_cut * m)
    lo = max(0.0, m - hi_cut * m)
    if lo > hi:
        lo = hi
    return r1(lo), r1(hi)


def baseline_of(dim):
    m = {'假设的合理性': 15, '建模的创造性': 25, '结果的正确性': 25, '文字表述的清晰性': 35}[STD_OF_DIM[dim]]
    n = {'假设的合理性': 5, '建模的创造性': 5, '结果的正确性': 6, '文字表述的清晰性': 7}[STD_OF_DIM[dim]]
    return m / n


